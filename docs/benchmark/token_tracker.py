#!/usr/bin/env python3
"""
Track token usage from Claude Code JSONL session files.
Designed for benchmarking MCP tools vs native tools.

TOKEN TYPES EXPLAINED:
- input_tokens: Total input tokens sent to API
- output_tokens: Tokens generated by Claude
- cache_creation_input_tokens: New content added to cache (charged at 1.25x input rate)
- cache_read_input_tokens: Content read from cache (charged at 0.1x input rate)

PRICING (Claude Opus 4 - default):
- Input:       $15.00 / 1M tokens
- Output:      $75.00 / 1M tokens
- Cache write: $18.75 / 1M tokens (1.25x input)
- Cache read:   $1.50 / 1M tokens (0.1x input)

PRICING (Claude Sonnet 4):
- Input:        $3.00 / 1M tokens
- Output:      $15.00 / 1M tokens
- Cache write:  $3.75 / 1M tokens
- Cache read:   $0.30 / 1M tokens

Usage:
    python token_tracker.py                    # Show session summary
    python token_tracker.py mark               # Get current line number (use before each step)
    python token_tracker.py since <line>       # Show usage since line number
    python token_tracker.py tool <line>        # Show per-tool breakdown since line
    python token_tracker.py cost <line>        # Show cost breakdown since line
    python token_tracker.py summary            # Full session summary
    python token_tracker.py --model sonnet ... # Use Sonnet pricing instead of Opus
"""
import json
import sys
from pathlib import Path
from collections import defaultdict
from dataclasses import dataclass
from typing import Optional

JSONL_PATH = Path.home() / ".claude/projects/C--Users-cbein-source-repos-RoslynMcpServer"

# Pricing per 1M tokens
@dataclass
class Pricing:
    input: float
    output: float
    cache_write: float
    cache_read: float
    name: str

OPUS_PRICING = Pricing(
    input=15.00,
    output=75.00,
    cache_write=18.75,  # 1.25x input
    cache_read=1.50,    # 0.1x input
    name="Opus 4"
)

SONNET_PRICING = Pricing(
    input=3.00,
    output=15.00,
    cache_write=3.75,
    cache_read=0.30,
    name="Sonnet 4"
)

@dataclass
class TokenUsage:
    input_tokens: int = 0
    output_tokens: int = 0
    cache_write_tokens: int = 0
    cache_read_tokens: int = 0

    def __add__(self, other):
        return TokenUsage(
            self.input_tokens + other.input_tokens,
            self.output_tokens + other.output_tokens,
            self.cache_write_tokens + other.cache_write_tokens,
            self.cache_read_tokens + other.cache_read_tokens,
        )

    @property
    def new_context_tokens(self):
        """Tokens that add new context (cache_write = new content being processed)."""
        return self.cache_write_tokens

    @property
    def total_input_billed(self):
        """Total input tokens for billing (cache_write charged at 1.25x, cache_read at 0.1x)."""
        # Note: input_tokens in API response already includes both cached and non-cached
        # cache_write and cache_read are subsets that get different pricing
        return self.input_tokens

    def calculate_cost(self, pricing: Pricing) -> dict:
        """Calculate cost breakdown using given pricing."""
        # Non-cached input = total input - cache_write - cache_read
        non_cached_input = max(0, self.input_tokens - self.cache_write_tokens - self.cache_read_tokens)

        cost_input = (non_cached_input / 1_000_000) * pricing.input
        cost_output = (self.output_tokens / 1_000_000) * pricing.output
        cost_cache_write = (self.cache_write_tokens / 1_000_000) * pricing.cache_write
        cost_cache_read = (self.cache_read_tokens / 1_000_000) * pricing.cache_read

        return {
            "input": cost_input,
            "output": cost_output,
            "cache_write": cost_cache_write,
            "cache_read": cost_cache_read,
            "total": cost_input + cost_output + cost_cache_write + cost_cache_read,
            "non_cached_input_tokens": non_cached_input,
        }


def get_latest_session():
    """Find the most recent session file."""
    files = list(JSONL_PATH.glob("*.jsonl"))
    if not files:
        return None
    return max(files, key=lambda f: f.stat().st_mtime)


def parse_session(session_file=None, start_line=0):
    """Parse session and extract per-message metrics."""
    if session_file is None:
        session_file = get_latest_session()

    if not session_file or not session_file.exists():
        return []

    messages = []
    with open(session_file, 'r', encoding='utf-8') as f:
        for i, line in enumerate(f):
            if i < start_line:
                continue
            try:
                data = json.loads(line)
                msg_type = data.get("type")
                message = data.get("message", {})

                entry = {
                    "line": i,
                    "type": msg_type,
                    "timestamp": data.get("timestamp"),
                }

                # Extract usage if present
                if "usage" in message:
                    usage = message["usage"]
                    entry["usage"] = TokenUsage(
                        input_tokens=usage.get("input_tokens", 0),
                        output_tokens=usage.get("output_tokens", 0),
                        cache_write_tokens=usage.get("cache_creation_input_tokens", 0),
                        cache_read_tokens=usage.get("cache_read_input_tokens", 0),
                    )

                # Extract tool info
                content = message.get("content", [])
                tools_in_message = []
                if isinstance(content, list):
                    for item in content:
                        if isinstance(item, dict):
                            if item.get("type") == "tool_use":
                                tools_in_message.append(item.get("name"))
                            elif item.get("type") == "tool_result":
                                entry["tool_result"] = True
                                result_content = item.get("content", "")
                                if isinstance(result_content, str):
                                    entry["result_chars"] = len(result_content)

                if tools_in_message:
                    entry["tool_calls"] = tools_in_message

                messages.append(entry)
            except json.JSONDecodeError:
                continue

    return messages


def analyze_tool_usage(messages):
    """
    Analyze per-tool token usage.

    Attribution logic:
    - When we see tool_use in a message, that's Claude calling a tool
    - The usage in THAT message is attributed to the tool(s) called
    - If multiple tools in one message, we split evenly (rare case)
    """
    tools = defaultdict(lambda: TokenUsage())
    tool_call_counts = defaultdict(int)

    for msg in messages:
        if "tool_calls" in msg and "usage" in msg:
            # This message has both tool calls and usage - attribute to tools
            num_tools = len(msg["tool_calls"])
            usage = msg["usage"]

            # Split usage among tools if multiple (usually just 1)
            per_tool = TokenUsage(
                input_tokens=usage.input_tokens // num_tools,
                output_tokens=usage.output_tokens // num_tools,
                cache_write_tokens=usage.cache_write_tokens // num_tools,
                cache_read_tokens=usage.cache_read_tokens // num_tools,
            )

            for tool_name in msg["tool_calls"]:
                tools[tool_name] = tools[tool_name] + per_tool
                tool_call_counts[tool_name] += 1

        elif "usage" in msg and "tool_calls" not in msg:
            # Usage without tool call - attribute to "conversation"
            tools["(conversation)"] = tools["(conversation)"] + msg["usage"]
            tool_call_counts["(conversation)"] += 1

    return dict(tools), dict(tool_call_counts)


def get_line_count(session_file=None):
    """Get current line count of session file."""
    if session_file is None:
        session_file = get_latest_session()
    if not session_file or not session_file.exists():
        return 0
    with open(session_file, 'r', encoding='utf-8') as f:
        return sum(1 for _ in f)


def format_tokens(n):
    """Format token count with K suffix."""
    if n >= 1000:
        return f"{n/1000:.1f}K"
    return str(n)


def format_cost(amount):
    """Format cost in dollars."""
    if amount < 0.01:
        return f"${amount:.4f}"
    return f"${amount:.2f}"


def print_usage_summary(usage: TokenUsage, pricing: Pricing, label=""):
    """Print a formatted usage summary with costs."""
    costs = usage.calculate_cost(pricing)

    # Total input = non-cached + cache_write + cache_read
    total_input = costs['non_cached_input_tokens'] + usage.cache_write_tokens + usage.cache_read_tokens
    total_all = total_input + usage.output_tokens

    if label:
        print(f"\n=== {label} ===")

    print(f"\n{'Token Type':<25} {'Tokens':>12} {'Cost':>10}")
    print("-" * 50)
    print(f"{'Input (non-cached)':<25} {format_tokens(costs['non_cached_input_tokens']):>12} {format_cost(costs['input']):>10}")
    print(f"{'Cache write (new)':<25} {format_tokens(usage.cache_write_tokens):>12} {format_cost(costs['cache_write']):>10}")
    print(f"{'Cache read (reused)':<25} {format_tokens(usage.cache_read_tokens):>12} {format_cost(costs['cache_read']):>10}")
    print("-" * 50)
    print(f"{'Total Input':<25} {format_tokens(total_input):>12} {format_cost(costs['input'] + costs['cache_write'] + costs['cache_read']):>10}")
    print(f"{'Output':<25} {format_tokens(usage.output_tokens):>12} {format_cost(costs['output']):>10}")
    print("-" * 50)
    print(f"{'TOTAL':<25} {format_tokens(total_all):>12} {format_cost(costs['total']):>10}")
    print(f"\nPricing model: {pricing.name}")


def main():
    # Check for --model flag
    pricing = OPUS_PRICING
    args = sys.argv[1:]
    if "--model" in args:
        idx = args.index("--model")
        if idx + 1 < len(args):
            model = args[idx + 1].lower()
            if model == "sonnet":
                pricing = SONNET_PRICING
            args = args[:idx] + args[idx+2:]

    if len(args) < 1:
        # Default: show current position
        count = get_line_count()
        session = get_latest_session()
        print(f"Session: {session.name if session else 'None'}")
        print(f"Current line: {count}")
        print(f"\nUsage: python token_tracker.py [mark|since|tool|cost|summary] [line]")
        return

    cmd = args[0]

    if cmd == "mark":
        count = get_line_count()
        print(f"MARK:{count}")
        print(f"(Use this number with 'since', 'tool', or 'cost' commands)")

    elif cmd == "since":
        start = int(args[1]) if len(args) > 1 else 0
        messages = parse_session(start_line=start)

        total = TokenUsage()
        tool_calls = 0

        for msg in messages:
            if "usage" in msg:
                total = total + msg["usage"]
            if "tool_calls" in msg:
                tool_calls += len(msg["tool_calls"])

        print(f"=== Usage Since Line {start} ===")
        print(f"Tool calls: {tool_calls}")
        print_usage_summary(total, pricing)

    elif cmd == "tool":
        start = int(args[1]) if len(args) > 1 else 0
        messages = parse_session(start_line=start)
        tools, counts = analyze_tool_usage(messages)

        print(f"=== Per-Tool Usage Since Line {start} ===")
        print(f"\n{'Tool':<45} {'Calls':>6} {'New Context':>12} {'Output':>10}")
        print("-" * 75)

        total = TokenUsage()
        total_calls = 0

        # Sort by new context (cache_write) descending
        sorted_tools = sorted(tools.items(), key=lambda x: -x[1].cache_write_tokens)

        for name, usage in sorted_tools:
            call_count = counts.get(name, 0)
            print(f"{name:<45} {call_count:>6} {format_tokens(usage.cache_write_tokens):>12} {format_tokens(usage.output_tokens):>10}")
            total = total + usage
            total_calls += call_count

        print("-" * 75)
        print(f"{'TOTAL':<45} {total_calls:>6} {format_tokens(total.cache_write_tokens):>12} {format_tokens(total.output_tokens):>10}")

        # Show cost summary
        costs = total.calculate_cost(pricing)
        print(f"\nTotal cost: {format_cost(costs['total'])} ({pricing.name} pricing)")

    elif cmd == "cost":
        start = int(args[1]) if len(args) > 1 else 0
        messages = parse_session(start_line=start)

        total = TokenUsage()
        for msg in messages:
            if "usage" in msg:
                total = total + msg["usage"]

        print_usage_summary(total, pricing, f"Cost Breakdown Since Line {start}")

    elif cmd == "summary":
        messages = parse_session()
        tools, counts = analyze_tool_usage(messages)

        total = TokenUsage()
        for usage in tools.values():
            total = total + usage

        print("=== Full Session Summary ===")
        print(f"Total messages: {len(messages)}")

        print(f"\n{'Tool':<45} {'Calls':>6} {'New Context':>12}")
        print("-" * 65)

        for name, usage in sorted(tools.items(), key=lambda x: -x[1].cache_write_tokens):
            if counts.get(name, 0) > 0:
                print(f"{name:<45} {counts[name]:>6} {format_tokens(usage.cache_write_tokens):>12}")

        print_usage_summary(total, pricing, "Session Totals")

    else:
        print(f"Unknown command: {cmd}")
        print(__doc__)


if __name__ == "__main__":
    main()
